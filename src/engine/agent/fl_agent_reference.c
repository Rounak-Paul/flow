#include "fl_agent_internal.h"

/* Sections of the manual; each stays below the portable string literal limit. */
const char *const FL_AGENT_REFERENCE[] = {
"# Flow authoring reference\n"
"\n"
"Flow is a motion-graphics and video editor. A project holds scenes; a scene is a canvas (default 1920x1080) holding\n"
"entities (shapes, text, images) arranged in a hierarchy, a timeline of beats, keyframe animation, audio clips and\n"
"optional Lua scripts. Everything is edited with `apply_ops`: atomic, undoable batches of typed operations.\n"
"\n",
"## Units and conventions\n"
"- Times and durations are SECONDS (decimals allowed). Rotation is DEGREES. Positions and sizes are scene pixels,\n"
"  local to the parent; the origin is the top-left corner of the canvas and y grows downward.\n"
"- Colours are \"#RRGGBB\" or \"#RRGGBBAA\" (or [r,g,b,a] with 0..255). Opacity is 0..1.\n"
"- Ids are integers. Inside one `apply_ops` batch, give a created object a name with `\"as\": \"$title\"` and use\n"
"  \"$title\" wherever an id is expected in later operations.\n"
"- Later entities in a scene draw on top of earlier ones. `entity.reorder` changes that order.\n"
"\n",
"## Workflow\n"
"1. `get_project` for scenes and assets, `get_scene` for one scene's full contents (use its `revision` in `expect`).\n"
"2. Build with `apply_ops`. Prefer one batch per logical change; a failing operation applies nothing and names the\n"
"   failing index. Use `dry_run: true` to validate a plan.\n"
"3. Check the result with `render_frame` (an image) and `evaluate_scene` (numbers). Fix and repeat.\n"
"4. `undo`/`redo` revert whole batches. They refuse when someone edited the project in between.\n"
"\n",
"## Scene time: beats\n"
"A scene's length is the sum of its beats; every scene starts with one 5 s beat. Beats are narrative steps. Keyframes\n"
"can anchor to a beat edge so they follow when the beat is retimed. Resizing a beat with `beat.update` scales the\n"
"keyframes inside it. Keyframe times must lie within 0..scene length, so create or extend beats first.\n"
"\n",
"## Operations (`apply_ops` `ops` items)\n"
"scene.add {name} -> id\n"
"scene.remove {scene} | scene.rename {scene,name} | scene.move {scene,position}\n"
"scene.set {scene, width?, height?, aspect?: [w,h]|null, camera?: [x,y]}\n"
"entity.create {scene, kind, parent?, asset?, props?} -> id\n"
"  kind: group, rectangle, ellipse, line, arrow, text, image (image needs asset = an image asset id)\n"
"entity.set {entity, props}      entity.remove {entity} (removes the subtree)\n"
"entity.reparent {entity, parent|null}      entity.reorder {entity, position}\n"
"  props: name, visible, x, y, width, height, rotation, scale_x, scale_y, opacity,\n"
"         fill, stroke, stroke_width (shapes), text, font_size, font_family, font_weight, italic (text), asset (image)\n"
"  Not every kind has every prop: groups have no fill; lines/arrows have a stroke but no fill; images only an asset.\n"
"  `set` changes BASE values. A property that has keyframes keeps following them; edit the keys instead.\n"
"key.set {entity, property, at, value, ease?, key?} -> key id\n"
"  property: x y width height rotation scale_x scale_y opacity fill stroke stroke_width font_size\n"
"  at: seconds, or {\"beat\": id, \"edge\": \"start\"|\"end\", \"offset\": seconds}\n"
"  ease: linear (default), in, out, in_out, hold. The ease shapes the segment from this key to the next.\n"
"  Setting a key at the time of an existing key replaces it. Values between keys are interpolated.\n"
"key.remove {key}      track.remove {entity, property}\n"
"beat.add {scene, name, duration, position?, auto_advance?} -> id      beat.update {beat, name?, duration?, auto_advance?}\n"
"beat.remove {beat}    beat.move {beat, position}    beat.split {beat, at, name} -> id of the new right-hand beat\n"
"clip.add {scene, asset, start?, source_offset?, duration?, gain?, fade_in?, fade_out?} -> id   (asset must be audio;\n"
"  duration 0 or omitted plays to the end of the asset; gain 0..4)\n"
"clip.update {clip, ...same fields}      clip.remove {clip}\n"
"script.set {entity, source, enabled?}   script.remove {entity}\n"
"\n",
"## Lua scripts\n"
"A script is pure: it defines `on_evaluate(self, time)` (time in seconds) and runs from scratch for every frame, so a\n"
"frame depends only on the document and the time. Nothing persists between calls. `self` starts from the entity's\n"
"base values with keyframes applied; changes you make are the final values.\n"
"  self.transform.{x,y,width,height,rotation(radians),scale_x,scale_y}\n"
"  self.appearance.{fill,stroke (arrays of 4 numbers 0..255), stroke_width, font_size}\n"
"  self.opacity, self.tick, self.duration (scene seconds), self.entity\n"
"Available: math, string, table, utf8, ipairs, pairs (stable order), select, tonumber, tostring, type, assert, error.\n"
"Not available: files, network, os, require, pcall, coroutines. math.random is deterministic per entity.\n"
"Limits: 1M instructions and 16 MiB per scene evaluation. Errors keep the keyframed values and are reported by\n"
"`evaluate_scene` as `script_error`.\n"
"Example: self.transform.y = self.transform.y + math.sin(time * 4) * 20\n"
"\n",
"## Assets\n"
"`import_asset {path}` copies a local image, audio, video or font file into the project and returns its id. Asset\n"
"imports are not part of undo. Images are placed with entity.create kind=image.\n"
"\n",
"## Errors\n"
"Failures return {error:{code,message}}: invalid_argument, unknown_field, missing_field, unknown_reference, not_found,\n"
"not_applicable, rejected (the document refused the values), revision_conflict, conflict (undo/redo refused), no_project.\n", NULL};
